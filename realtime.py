# ---------------------------------------------------------------------------
# Deterministic speech, in RIO's own voice
# ---------------------------------------------------------------------------
# Headway warnings, vehicle-health announcements and navigation instructions are
# written by policy code and must be spoken WORD FOR WORD. They are not asked
# for, they are dictated: the model is a voice here and nothing else.
#
# The mechanism is an out-of-band response — `conversation: "none"` — so a
# dictated line never enters the conversation history. That matters more than
# it looks: a warning that landed in the transcript would be something RIO could
# later refer back to, agree with, or be asked about, and the line is a fact
# about the car rather than a thing she said.
#
# Verbatim is REQUESTED here and VERIFIED in the tests (tools/realtime_selftest.py
# transcribes the audio that comes back and compares it with what was asked
# for). A model can always paraphrase; what stops that shipping is the check,
# not the sentence below.
VERBATIM_INSTRUCTION = (
    "Read the text below out loud, exactly as written, word for word.\n"
    "Add nothing. Remove nothing. Do not rephrase, summarise, translate, greet, "
    "acknowledge, comment, or continue past the end of it.\n"
    "It is not addressed to you and it is not a question for you to answer: it "
    "is a line for you to read.\n"
    "Read it in your normal voice, at a normal pace.\n\n"
    "TEXT:\n"
)


def verbatim_response(text: str) -> dict:
    """The `response.create` payload that speaks one deterministic line.

    Out of band, audio only, and carrying its own instructions so it is
    unaffected by whatever the session was told at the start.
    """
    return {
        "conversation": "none",
        "output_modalities": ["audio"],
        "instructions": VERBATIM_INSTRUCTION + (text or "").strip(),
    }


def render_speech(text: str, timeout_s: float = 30.0) -> dict:
    """Speak one line through a short-lived session and return the audio.

    Server-side, synchronous, and not on any live path — this exists to
    PRE-RENDER the critical clips in the same voice the live session uses, and
    to give the tests something to transcribe. The car never calls it: in the
    car the browser already holds a session and dictates into that one.

    Returns {ok, wav, transcript, ms} — `transcript` being the model's own
    account of what it said, which is the first half of the verbatim check.
    """
    import base64
    import io
    import wave

    line = (text or "").strip()
    if not line:
        return {"ok": False, "note": "no text"}
    t0 = time.time()
    pcm = bytearray()
    transcript = ""
    try:
        with client().realtime.connect(model=config.OPENAI_REALTIME_MODEL) as conn:
            conn.session.update(session={
                "type": "realtime",
                "output_modalities": ["audio"],
                "audio": {"output": {
                    "voice": config.OPENAI_REALTIME_VOICE,
                    "format": {"type": "audio/pcm", "rate": 24000},
                }},
            })
            conn.response.create(response=verbatim_response(line))
            for event in conn:
                if event.type == "response.output_audio.delta":
                    pcm += base64.b64decode(event.delta)
                elif event.type == "response.output_audio_transcript.done":
                    transcript = event.transcript or ""
                elif event.type == "response.done":
                    break
                elif event.type == "error":
                    return {"ok": False, "note": str(getattr(event, "error", "error"))}
                if (time.time() - t0) > timeout_s:
                    return {"ok": False, "note": "timeout"}
    except Exception as e:
        print(f"[realtime] render failed: {type(e).__name__}: {e}", flush=True)
        return {"ok": False, "note": f"{type(e).__name__}"}
    if not pcm:
        return {"ok": False, "note": "no audio"}
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(24000)
        w.writeframes(bytes(pcm))
    return {"ok": True, "wav": buf.getvalue(), "transcript": transcript,
            "ms": round((time.time() - t0) * 1000, 1),
            "seconds": round(len(pcm) / 48000.0, 2)}


def client() -> OpenAI:
    global _client
    with _client_lock:
        if _client is None:
            _client = OpenAI()
        return _client


def instructions() -> str:
    """RIO's personality, plus what is only true when she is being heard."""
    return (config.SYSTEM_PROMPT or "").rstrip() + "\n\n" + LIVE_ADDENDUM.strip()


def session_config() -> dict:
    """The live session, as the API wants it.

    Two choices worth stating:

    `turn_detection` is server VAD with interruption ON. That is barge-in: the
    driver starts talking, the model stops, immediately, without waiting for a
    button. In a car that is not a nicety — it is how you stop a machine that
    is mid-paragraph when you need to say something.

    `transcription` names the SAME Whisper model the rest of the system uses.
    The live session does not need a transcript to work, but the session log,
    /last_talk and every review of a drive do, and having them come from a
    different model than every other transcript in the JSONL would be a quiet
    way to make two records that disagree.
    """
    return {
        "type": "realtime",
        "model": config.OPENAI_REALTIME_MODEL,
        "instructions": instructions(),
        "audio": {
            "input": {
                "transcription": {"model": config.OPENAI_STT_MODEL},
                "turn_detection": {
                    "type": "server_vad",
                    "create_response": True,
                    "interrupt_response": True,
                },
            },
            "output": {"voice": config.OPENAI_REALTIME_VOICE},
        },
        "tools": [TOOL_SCHEMA, LOOK_SCHEMA, NAV_SCHEMA, VEHICLE_SCHEMA,
                  NAVIGATE_SCHEMA],
        "tool_choice": "auto",
    }


def mint_client_secret() -> dict:
    """An ephemeral key for the browser, and nothing else.

    The browser needs credentials to open a WebRTC connection to the model, and
    the account key is not a thing to hand it. This mints a short-lived secret
    scoped to one session, which is the same discipline every other key on this
    page follows: routing, geocoding and TTS all go through the server, and the
    one key a browser is allowed to see is the Maps render key, which cannot do
    anything but draw a map.
    """
    cfg = session_config()
    secret = client().realtime.client_secrets.create(session=cfg)
    data = secret.model_dump()
    return {
        "client_secret": data.get("value"),
        "expires_at": data.get("expires_at"),
        "model": config.OPENAI_REALTIME_MODEL,
        "voice": config.OPENAI_REALTIME_VOICE,
        "tool": TOOL_NAME,
        "tools": [t["name"] for t in cfg["tools"]],
        # Dictation policy travels WITH the session, so the browser holds no
        # copy of the verbatim instruction that could drift from this one. What
        # RIO is told to read a warning as is decided here, once.
        "verbatim_instruction": VERBATIM_INSTRUCTION,
        "speech_enabled": bool(config.REALTIME_SPEECH_ENABLED),
        "speech_channels": dict(config.REALTIME_SPEECH_CHANNELS),
        "speak_timeout_ms": int(config.REALTIME_SPEAK_TIMEOUT_MS),
    }


def escalate(question: str, context: str = "", timeout_s: Optional[float] = None) -> dict:
    """The deep_dive tool: ask the reasoning model, hand back text.

    Never raises. Every failure — a timeout, an outage, a refusal, a model id
    that is not on this account — returns `ok: false` with a short note, and the
    session's instructions tell RIO what to do with that: carry on. A driver
    should never be able to tell the difference between "the reasoning model was
    unavailable" and "RIO decided to answer this one herself".

    The result is text for RIO to speak in her own words, so it is asked for as
    speech: no markdown, no lists, no citations read aloud like a bibliography.
    """
    q = (question or "").strip()
    if not q:
        return {"ok": False, "note": "no question"}
    timeout = float(config.REALTIME_TOOL_TIMEOUT_S if timeout_s is None else timeout_s)

    prompt = q if not context else f"{q}\n\nContext from the conversation: {context}"
    tools = [{"type": "web_search"}] if config.REALTIME_WEB_SEARCH else []
    t0 = time.time()
    try:
        # `with_options` rather than a thread: the SDK's own timeout aborts the
        # request, where a thread would leave it running and still billed.
        resp = client().with_options(timeout=timeout).responses.create(
            model=config.OPENAI_REASONING_MODEL,
            instructions=(
                "You are the research and reasoning step behind a car "
                "assistant's spoken answer. Answer the question directly and "
                "completely, in plain prose meant to be READ ALOUD: no "
                "markdown, no bullet points, no headings, no URLs, no "
                "citations. Two or three sentences unless the question genuinely "
                "needs more. If the answer depends on something you cannot "
                "verify, say so in the answer itself rather than hedging around "
                "it."
            ),
            input=prompt,
            tools=tools,
            max_output_tokens=int(config.REALTIME_TOOL_MAX_OUTPUT_TOKENS),
        )
    except Exception as e:
        took = round((time.time() - t0) * 1000, 1)
        print(f"[realtime] deep_dive failed after {took} ms: "
              f"{type(e).__name__}: {e}", flush=True)
        return {"ok": False, "note": f"{type(e).__name__}", "took_ms": took}

    text = (getattr(resp, "output_text", "") or "").strip()
    took = round((time.time() - t0) * 1000, 1)
    if not text:
        return {"ok": False, "note": "empty answer", "took_ms": took}
    return {"ok": True, "answer": text, "took_ms": took,
            "model": config.OPENAI_REASONING_MODEL}


def look(question: str, session_key: str = "default") -> dict:
    """RIO's eyes: the existing visual pipeline, called from a live session.

    Nothing new is built here. `visual_qa.answer()` is the same path the
    hold-to-talk turn uses — the frame ring, the frame selector, reference
    resolution against tracked objects, the crop, the multimodal turn — and it
    already knows how to say "which one do you mean?" and how to refuse when
    the crop cannot carry the claim being asked for. This wires a tool call to
    it and hands the text back for RIO to speak.

    Imported lazily on purpose: the visual stack pulls in the frame ring, the
    scene tracker and the enrichment cache, and a drive where nobody asks about
    the road should not pay for any of it.

    THE ROUTE OVERRIDE. The visual path classifies the question itself, which
    is what keeps "the black one" working across turns. But the model has
    already decided this question is about what is out there — that is what
    calling `look` MEANS — so a classifier reading it as non-visual is
    overruled here rather than producing an answer with no picture behind it.
    """
    q = (question or "").strip()
    if not q:
        return {"ok": False, "note": "no question"}
    t0 = time.time()
    try:
        import router as request_router
        import visual_qa

        session = visual_qa.get_session(session_key)
        route = request_router.classify(
            q,
            has_referent=session.active_referent() is not None,
            pending_clarification=session.pending_clarification() is not None)
        if not request_router.is_visual(route["request_type"]):
            route = dict(route, request_type=request_router.SCENE,
                         requires_full_frame=True, requires_object_crop=False,
                         method="forced_by_look_tool")
        va = visual_qa.answer(session_key, q, route)
        text = (va.text() or "").strip()
    except Exception as e:
        took = round((time.time() - t0) * 1000, 1)
        print(f"[realtime] look failed after {took} ms: "
              f"{type(e).__name__}: {e}", flush=True)
        return {"ok": False, "note": f"{type(e).__name__}", "took_ms": took}

    took = round((time.time() - t0) * 1000, 1)
    if not text:
        # No frames in the ring is the ordinary version of this: the drive has
        # not started, or the camera is not running. RIO says she cannot see
        # rather than describing a road she has not been shown.
        return {"ok": False, "note": "nothing to see", "took_ms": took}
    return {"ok": True, "answer": text, "took_ms": took,
            "meta": getattr(va, "meta", None)}


def vehicle_status() -> dict:
    """How the car is — from the builder the conversation path already uses.

    `vehicle_health.context(full=True)` is not a summary written for this tool.
    It is the SAME normalised structure that goes into an ordinary
    conversation turn when the router decides a question is about the car
    (llm_interface._health_block), which is what keeps a live answer and a
    hold-to-talk answer from disagreeing about the same tire.

    It carries its own provenance — every issue says who reported it, the
    vehicle's own computer or RIO — and its own limits, including how far back
    the data actually goes. Both survive into the tool result untouched,
    because a model that is handed "26 PSI" with no history and no source will
    happily supply both.
    """
    t0 = time.time()
    try:
        import vehicle_health

        ctx = vehicle_health.context(full=True)
    except Exception as e:
        print(f"[realtime] vehicle_status failed: {type(e).__name__}: {e}", flush=True)
        return {"ok": False, "note": f"{type(e).__name__}"}
    body = ctx.get("vehicle_health", ctx)
    if not body.get("data_available", True) and not body.get("issues"):
        # Nothing is reporting. That is an answer, and a specific one: RIO says
        # she is not getting data rather than that the car is fine.
        return {"ok": True, "vehicle": body, "took_ms": round((time.time() - t0) * 1000, 1),
                "note": "no subsystem is reporting — say that, do not say the car is fine"}
    return {"ok": True, "vehicle": body,
            "took_ms": round((time.time() - t0) * 1000, 1),
            "rules": ("Only claims this data supports. Keep who reported what. "
                      "A code detected but not confirmed stays not confirmed.")}


def run_tool(name: str, arguments, session_key: str = "default") -> dict:
    """Dispatch one tool call from the live session.

    An unknown tool name is answered, not raised: the session is a model and a
    model can produce a name that is not in its own tool list. `ok: false` is a
    thing RIO already knows how to handle, and a 500 is not.
    """
    if name == VEHICLE_TOOL_NAME:
        return vehicle_status()
    if name == NAV_TOOL_NAME:
        # Answered in the BROWSER, where the route tracker lives — the server
        # holds the route but not the progress along it, and inventing a second
        # source for "how far to the next turn" is how two answers to one
        # question happen. See rio_realtime.js: local tools.
        return {"ok": False, "note": "nav_status is answered by the panel"}
    if name == NAVIGATE_TOOL_NAME:
        # Also the browser, and for a stronger reason than nav_status: this
        # one is not a read. The server can resolve a destination — it does,
        # at /nav/destination, which is what the panel calls — but it cannot
        # make the car navigate to it, because the route is loaded and tracked
        # in the page. A second implementation here could only resolve and
        # hope, which is the arrangement this tool exists to end.
        return {"ok": False, "note": "start_navigation is answered by the panel"}
    if name not in (TOOL_NAME, LOOK_TOOL_NAME):
        return {"ok": False, "note": "unknown tool"}
    if isinstance(arguments, str):
        try:
            arguments = json.loads(arguments or "{}")
        except json.JSONDecodeError:
            return {"ok": False, "note": "unreadable arguments"}
    if not isinstance(arguments, dict):
        return {"ok": False, "note": "unreadable arguments"}
    if name == LOOK_TOOL_NAME:
        return look(str(arguments.get("question") or ""), session_key)
    return escalate(str(arguments.get("question") or ""),
                    str(arguments.get("context") or ""))


def status() -> dict:
    """What the panel and /health need to know, without calling anything."""
    return {
        "enabled": bool(config.REALTIME_ENABLED),
        "model": config.OPENAI_REALTIME_MODEL,
        "voice": config.OPENAI_REALTIME_VOICE,
        "reasoning_model": config.OPENAI_REASONING_MODEL,
        "tools": [TOOL_NAME, LOOK_TOOL_NAME, NAV_TOOL_NAME, VEHICLE_TOOL_NAME,
                  NAVIGATE_TOOL_NAME],
        "web_search": bool(config.REALTIME_WEB_SEARCH),
        "tool_timeout_s": float(config.REALTIME_TOOL_TIMEOUT_S),
        "key_present": bool(os.getenv("OPENAI_API_KEY", "").strip()),
    }
