"""RIO live: one speech-to-speech session, and the things she can reach for.

WHAT CHANGED, AND WHAT DID NOT
------------------------------
The conversation path used to be three models in a line — Whisper heard the
driver, a chat model thought, ElevenLabs spoke — and every turn paid all three
latencies in series, with a push-to-talk button holding the whole thing
together. The realtime model is all three at once: the driver's audio goes in,
RIO's audio comes out, and either of them can interrupt the other mid-word.

What did NOT change is everything that speaks deterministically. Headway
warnings, vehicle-health announcements and navigation instructions are
generated by policy code, spoken from fixed tables, and arbitrated exactly as
before. No model is anywhere near them, and this file must never become a way
in. RIO's live voice is conversation, and conversation is the tier that yields.

THE ESCALATION
--------------
Some questions want more than a fast conversational model should attempt: what
is actually open at this hour, what a fault code really means, anything needing
the web or a chain of reasoning. For those the realtime session calls ONE tool,
which asks the reasoning model and hands back text.

The driver never learns any of this happened. There is no second voice, no
"let me ask my research model" — RIO says something while it runs, then speaks
the answer as her own. And if it fails, times out, or is switched off, she
carries on and answers from what she already has: the tool returning
`ok: false` is an ordinary outcome the instructions tell her how to handle,
not an error the driver hears about.

AND ONE THING SHE DOES
----------------------
The rest of her tools are reads: the camera, the route, the car, the reasoning
model. `start_navigation` is not. Asked to be taken somewhere, RIO sets the
destination herself, through the same path the dashboard's destination box
uses, and confirms it — where she used to describe the route and tell the
driver to set it themselves.

That is not a crack in the rule above. Announcing is speaking unasked;
routing is doing what was asked. The turns are the part that does not move:
navigation calls those, out loud, from its own tables, and nothing here may
become a way in.
"""
